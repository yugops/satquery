    "def parse_labels(raw):",
    "    if isinstance(raw, str):",
    "        raw = raw.strip()",
    "        if raw.startswith('[') and raw.endswith(']'):",
    "            try:",
    "                raw = ast.literal_eval(raw)",
    "            except Exception:",
    "                raw = [x.strip(\" '\") for x in raw[1:-1].split(',')]",
